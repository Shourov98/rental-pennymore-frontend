// Auth state management for both Agent and Renter flows.
import { createSlice, PayloadAction } from "@reduxjs/toolkit";
import type { RootState } from "../store";

type Role = "Agent" | "Renter";

export interface UserBase {
  _id: string;
  email: string;
  fullName: string;
  title?: string | null;
  phone: string;
  role: Role;
  accountStatus: "active" | "pending" | "suspended";
  emailVerified: boolean;
  lastLoginAt?: string;
  profileImage?: string | null;
  profileImageUrl?: string | null;
  referralCode?: string | null;
  referralLink?: string | null;
  totalReferrals?: number;
  emailSubscriptionEnabled?: boolean;
  passwordAutoGenerated?: boolean;
  mustChangePassword?: boolean;
  createdAt: string;
  updatedAt: string;
}

export interface RenterProfile {
  _id: string;
  userId: string;
  email: string;
  fullName: string;
  phoneNumber: string;
  registrationType: "normal" | "social";
  petFriendly: boolean;
  emailSubscriptionEnabled?: boolean;
  createdAt: string;
  updatedAt: string;
}

export interface AgentProfileUser {
  _id: string;
  email: string;
  phoneNumber: string;
  fullName: string;
  role: "Agent" | string;
  accountStatus: "active" | "pending" | "suspended" | string;
  totalReferrals?: number;
  emailVerified?: boolean;
  referralCode?: string;
  referralLink?: string;
  canRefer?: boolean;
  profileImageUrl?: string;
  profileImage?: string | null;
  id?: string;
}

export interface AgentProfile {
  _id: string;
  userInfo: AgentProfileUser;
  userId?: AgentProfileUser;
  title?: string | null;
  licenseNumber?: string;
  brokerageName?: string;
  isActive?: boolean;
  totalRentersReferred?: number;
  activeReferrals?: number;
  referralConversionRate?: number;
  hasGrantAccess?: boolean;
  lastAccessToggleAt?: string;
  grantAccessCount?: number;
  totalMatches?: number;
  successfulMatches?: number;
  profileCompleteness?: number;
  createdAt?: string;
  updatedAt?: string;
}

export interface ReferralInfo {
  registrationType?: string;
  referrer?: {
    id?: string;
    role?: string;
    fullName?: string;
    title?: string | null;
    brokerageName?: string | null;
    activationLink?: string | null;
    email?: string;
    phoneNumber?: string;
    referralCode?: string;
    [key: string]: unknown;
  } | null;
}

export interface Tokens {
  accessToken: string;
  refreshToken?: string;
  expiresIn?: string; // e.g. "7d"
}

export interface AuthState {
  user: UserBase | null;
  renter: RenterProfile | null;
  agentProfile: AgentProfile | null;
  role: Role | null;
  accessToken: string | null;
  refreshToken: string | null;
  expiresIn: string | null;
  mustChangePassword: boolean;
  referralInfo: ReferralInfo | null;
  referrer: ReferralInfo["referrer"] | null;
  referralRegistrationType: string | null;
  referrerName: string | null;
  referrerTitle: string | null;
  referrerBrokerageName: string | null;
  sessionReady: boolean;
  status: "idle" | "loading" | "authenticated" | "error";
  error: string | null;
}

const initialState: AuthState = {
  user: null,
  renter: null,
  agentProfile: null,
  role: null,
  accessToken: null,
  refreshToken: null,
  expiresIn: null,
  mustChangePassword: false,
  referralInfo: null,
  referrer: null,
  referralRegistrationType: null,
  referrerName: null,
  referrerTitle: null,
  referrerBrokerageName: null,
  sessionReady: false,
  status: "idle",
  error: null,
};

export type AgentLoginPayload = {
  user: UserBase;
  accessToken: string;
  expiresIn: string;
  mustChangePassword: boolean;
  title?: string | null;
  agentProfile?: AgentProfile | null;
};

export type RenterLoginPayload = {
  user: UserBase;
  renter?: RenterProfile | null;
  tokens?: Tokens;
  accessToken?: string;
  refreshToken?: string;
  expiresIn?: string;
  registrationType: "normal" | "social";
  referralInfo?: ReferralInfo | null;
};

const authSlice = createSlice({
  name: "auth",
  initialState,
  reducers: {
    authStart(state) {
      state.status = "loading";
      state.error = null;
    },
    sessionChecked(state) {
      state.sessionReady = true;
    },
    agentLoginSuccess(state, action: PayloadAction<AgentLoginPayload>) {
      const {
        user,
        accessToken,
        expiresIn,
        mustChangePassword,
        title,
        agentProfile,
      } =
        action.payload;
      state.user = {
        ...user,
        title: user.title ?? title ?? null,
        profileImage: user.profileImage ?? user.profileImageUrl ?? null,
      };
      state.agentProfile = agentProfile ?? null;
      state.role = user.role;
      state.renter = null;
      state.accessToken = accessToken;
      state.refreshToken = null;
      state.expiresIn = expiresIn;
      state.mustChangePassword = !!mustChangePassword;
      state.referralInfo = null;
      state.referrer = null;
      state.referralRegistrationType = null;
      state.referrerName = null;
      state.referrerTitle = null;
      state.referrerBrokerageName = null;
      state.sessionReady = true;
      state.status = "authenticated";
      state.error = null;
    },
    renterLoginSuccess(state, action: PayloadAction<RenterLoginPayload>) {
      const { user, renter } = action.payload;
      const tokens =
        action.payload.tokens ??
        (action.payload.accessToken
          ? {
              accessToken: action.payload.accessToken,
              refreshToken: action.payload.refreshToken,
              expiresIn: action.payload.expiresIn,
            }
          : null);
      const referralInfo = action.payload.referralInfo;
      state.user = {
        ...user,
        profileImage: user.profileImage ?? user.profileImageUrl ?? null,
      };
      state.agentProfile = null;
      state.role = user.role;
      state.renter = renter ?? null;
      state.accessToken = tokens?.accessToken ?? null;
      state.refreshToken = tokens?.refreshToken ?? null;
      state.expiresIn = tokens?.expiresIn ?? null;
      state.mustChangePassword = !!user.mustChangePassword;
      state.referralInfo = referralInfo ?? null;
      state.referrer = referralInfo?.referrer ?? null;
      state.referralRegistrationType = referralInfo?.registrationType ?? null;
      state.referrerName = state.referrer?.fullName ?? null;
      state.referrerTitle = state.referrer?.title ?? null;
      state.referrerBrokerageName = state.referrer?.brokerageName ?? null;
      state.sessionReady = true;
      state.status = "authenticated";
      state.error = null;
    },
    refreshSuccess(state, action: PayloadAction<Tokens>) {
      state.accessToken = action.payload.accessToken;
      state.refreshToken = action.payload.refreshToken ?? state.refreshToken;
      state.expiresIn = action.payload.expiresIn ?? state.expiresIn;
      state.sessionReady = true;
      state.status = "authenticated";
      state.error = null;
    },
    authFailure(state, action: PayloadAction<string>) {
      state.status = "error";
      state.error = action.payload;
    },
    logout(state) {
      Object.assign(state, initialState);
      state.sessionReady = true;
    },
    updateUser(state, action: PayloadAction<Partial<UserBase>>) {
      if (state.user) {
        state.user = { ...state.user, ...action.payload };
      }
    },
    setAgentProfile(state, action: PayloadAction<AgentProfile | null>) {
      state.agentProfile = action.payload;
    },
    updateRenter(state, action: PayloadAction<Partial<RenterProfile>>) {
      if (state.renter) {
        state.renter = { ...state.renter, ...action.payload };
      }
    },
    setAuthFromProfile(state, action: PayloadAction<UserBase | RenterProfile>) {
      const profile = action.payload;
      if ("role" in profile) {
        state.user = {
          ...profile,
          profileImage: profile.profileImage ?? profile.profileImageUrl ?? null,
          emailSubscriptionEnabled:
            profile.emailSubscriptionEnabled ??
            state.user?.emailSubscriptionEnabled,
        };
        state.role = profile.role;
      } else {
        state.renter = {
          ...profile,
          emailSubscriptionEnabled:
            profile.emailSubscriptionEnabled ??
            state.renter?.emailSubscriptionEnabled,
        };
        state.role = "Renter";
      }
      state.sessionReady = true;
      state.status = "authenticated";
      state.error = null;
    },
  },
});

export const {
  authStart,
  sessionChecked,
  agentLoginSuccess,
  renterLoginSuccess,
  refreshSuccess,
  authFailure,
  logout,
  updateUser,
  setAgentProfile,
  updateRenter,
  setAuthFromProfile,
} = authSlice.actions;

export default authSlice.reducer;

// Selectors
export const selectAuth = (state: RootState) => state.auth;
export const selectUser = (state: RootState) => state.auth.user;
export const selectRenter = (state: RootState) => state.auth.renter;
export const selectAccessToken = (state: RootState) => state.auth.accessToken;
export const selectSessionReady = (state: RootState) => state.auth.sessionReady;
export const selectIsAuthed = (state: RootState) =>
  state.auth.status === "authenticated" &&
  !!state.auth.accessToken &&
  !!(state.auth.user || state.auth.renter);
export const selectReferralRegistrationType = (state: RootState) =>
  state.auth.referralRegistrationType;
export const selectReferralInfo = (state: RootState) => state.auth.referralInfo;
export const selectReferrer = (state: RootState) => state.auth.referrer;
export const selectAuthAgentProfile = (state: RootState) =>
  state.auth.agentProfile;
export const selectAgentHasGrantAccess = (state: RootState) =>
  state.auth.agentProfile?.hasGrantAccess ?? null;
export const selectReferrerName = (state: RootState) =>
  state.auth.referrerName;
export const selectReferrerTitle = (state: RootState) =>
  state.auth.referrerTitle;
export const selectReferrerBrokerageName = (state: RootState) =>
  state.auth.referrerBrokerageName;
